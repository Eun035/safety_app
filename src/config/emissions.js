/**
 * 탄소 절감량 산출 계수 — 단일 출처.
 *
 * 이전에는 같은 지표를 코드 곳곳에서 서로 다른 계수로 계산하고 있었다.
 * (useRideSession·App·ShadowImpactSheet는 0.2, generateMockRide는 0.13)
 * 둘 다 근거가 적혀 있지 않아, 화면마다 다른 숫자가 나올 수 있었다.
 *
 * ── 기준: 순 절감량 ─────────────────────────────────────────────────────
 * "PM으로 1km를 이동해 승용차 1km 주행을 대체했을 때 실제로 줄어드는 CO₂"
 *   = 승용차 배출 − PM 자체 배출
 *   = 125.2 g/km − 약 25 g/km ≈ **100 g/km = 0.100 kg/km**
 *
 * (1) 승용차 평균 온실가스 배출량 **125.2 g/km**
 *   - 2020년 국내 판매 10인승 이하 승용·승합차 실적 평균(환경부 자동차
 *     온실가스 관리제도). 같은 해 기준치 97 g/km를 29% 초과한 실측 평균이라,
 *     제도 기준치보다 실제 주행에 가깝다.
 *   - 출처: 대한민국 정책브리핑
 *     https://www.korea.kr/news/policyNewsView.do?newsId=148908381
 *
 * (2) 전동킥보드 전 생애주기 배출 **약 25 g/km**를 차감했다.
 *
 * ── 주의: 25 g/km는 유리한 쪽 가정이다 ──────────────────────────────────
 * PM의 생애주기 배출은 편차가 매우 크다.
 *   - 개인 소유 / 수명이 긴 기기: 약 20~25 g/km
 *   - 공유형: 약 30~124 g/km (제조와 재배치 운영이 지배적)
 * 즉 차감값 25는 '개인 소유 또는 잘 운영되는 공유 기기' 수준을 가정한 값이다.
 * 재배치가 잦거나 기기 수명이 짧은 공유 운영에서는 순 절감이 이보다
 * 훨씬 작아지고, 최악의 경우 0에 가까워질 수 있다.
 *
 * 대외 문서(제안서 등)에 인용할 때는 '승용차 대체 기준 순 절감량이며,
 * PM 배출을 25 g/km로 가정했다'는 전제를 함께 밝히는 것이 정확하다.
 * 실증에서 실제 기기 수명·재배치 데이터가 확보되면 이 값을 갱신할 것.
 */
export const CO2_AVOIDED_KG_PER_KM = 0.100;

/** 거리(km) → 회피 CO₂(kg). 음수·NaN 입력은 0으로 처리한다. */
export const co2AvoidedKg = (distanceKm) => {
    const d = Number(distanceKm);
    if (!Number.isFinite(d) || d <= 0) return 0;
    return d * CO2_AVOIDED_KG_PER_KM;
};
