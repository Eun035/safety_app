/**
 * 탄소 절감량 산출 계수 — 단일 출처.
 *
 * 이전에는 같은 지표를 코드 곳곳에서 서로 다른 계수로 계산하고 있었다.
 * (useRideSession·App·ShadowImpactSheet는 0.2, generateMockRide는 0.13)
 * 둘 다 근거가 적혀 있지 않아, 화면마다 다른 숫자가 나올 수 있었다.
 *
 * ── 기준 ────────────────────────────────────────────────────────────────
 * "PM으로 1km를 이동해 승용차 1km 주행을 대체했을 때 회피되는 CO₂"
 *
 * 승용차 평균 온실가스 배출량 **125.2 g/km**
 *   - 2020년 국내 판매 10인승 이하 승용·승합차 실적 평균(환경부 자동차
 *     온실가스 관리제도). 같은 해 기준치 97 g/km를 29% 초과한 실측 평균이라,
 *     제도 기준치보다 실제 주행에 가깝다.
 *   - 출처: 대한민국 정책브리핑
 *     https://www.korea.kr/news/policyNewsView.do?newsId=148908381
 *
 * ── 주의: 이 값은 '회피 배출량(총량)'이다 ───────────────────────────────
 * PM 자체의 배출을 빼지 않은 값이다. 전동킥보드의 전 생애주기 배출은
 * 편차가 매우 크다.
 *   - 개인 소유: 약 20~25 g/km
 *   - 공유형: 약 30~124 g/km (제조와 재배치 운영이 지배적)
 * 따라서 순 절감량을 쓰려면 위 범위를 빼야 하며, 공유 PM은 수명·재배치
 * 조건에 따라 절감 폭이 크게 줄어든다.
 *
 * 대외 문서(제안서 등)에 이 수치를 인용할 때는 '승용차 대체 기준 회피
 * 배출량'임을 함께 밝히는 것이 정확하다.
 */
export const CO2_AVOIDED_KG_PER_KM = 0.125;

/** 거리(km) → 회피 CO₂(kg). 음수·NaN 입력은 0으로 처리한다. */
export const co2AvoidedKg = (distanceKm) => {
    const d = Number(distanceKm);
    if (!Number.isFinite(d) || d <= 0) return 0;
    return d * CO2_AVOIDED_KG_PER_KM;
};
